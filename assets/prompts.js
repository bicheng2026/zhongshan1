  /* 统一出口：保证 messages[0] 恒为 system，云 SDK 硬性要求 */
  P.buildChat = function (spec, history) {
    var msgs = [{ role: 'system', content: spec.system }];
    (history || []).slice(-8).forEach(function (m) {
      if (m && (m.role === 'user' || m.role === 'assistant') && m.content) {
        msgs.push({ role: m.role, content: String(m.content).slice(0, 6000) });
      }
    });
    msgs.push({ role: 'user', content: spec.user });
    return msgs;
  };

