  var byId = {}, bySubject = {}, subjects = [];
  N.forEach(function (n) {
    byId[n.id] = n;
    if (!bySubject[n.subject]) { bySubject[n.subject] = []; subjects.push(n.subject); }
    bySubject[n.subject].push(n);
  });

  var API = {
    all: function () { return N.slice(); },
    byId: function (id) { return byId[id] || null; },
    bySubject: function (s) { return s ? (bySubject[s] || []).slice() : N.slice(); },
    subjects: function () { return subjects.slice(); },
    /* 直接前置 */
    pre: function (id) {
      var n = byId[id]; if (!n) return [];
      return (n.pre || []).map(function (x) { return byId[x]; }).filter(Boolean);
    },
    /* 直接后继（谁把我当前置） */
    next: function (id) {
      return N.filter(function (n) { return (n.pre || []).indexOf(id) >= 0; });
    },
    /* 递归收集全部祖先前置；depth 越大＝越基础的先修课。
       按 depth 降序返回，保证「补漏先看最底层」：先修课 → 直接前置 → 当前知识点。 */
    ancestors: function (id) {
      var seen = {}, out = [];
      (function walk(x, depth) {
        var n = byId[x]; if (!n) return;
        (n.pre || []).forEach(function (p) {
          if (seen[p]) return;
          seen[p] = true;
          var pn = byId[p]; if (!pn) return;
          out.push({ node: pn, depth: depth + 1 });
          walk(p, depth + 1);
        });
      })(id, 0);
      return out.sort(function (a, b) { return b.depth - a.depth || a.node.level - b.node.level; });
    },
    /* 从知识点 tags 反查题库里相关题目；subject/region 由调用方给。
       题目标签是明确标注，权重高于题干里偶然出现的词，避免"求函数的单调区间"被
       "函数"二字抢走本该归给"导数与单调性"的题。 */
    matchQuestions: function (node, pool, limit) {
      var tags = (node.tags || []).concat([node.name]);
      var scored = pool.map(function (q) {
        var qt = (q.tags || []).join(' ');
        var hay = qt + ' ' + (q.stem || '') + ' ' + (q.source || '');
        var hit = 0;
        tags.forEach(function (t) {
          if (!t) return;
          if (qt.indexOf(t) >= 0) hit += 5;
          else if (hay.indexOf(t) >= 0) hit += 1;
        });
        return { q: q, hit: hit };
      }).filter(function (x) { return x.hit > 0; });
      scored.sort(function (a, b) { return b.hit - a.hit; });
      return scored.slice(0, limit || 5).map(function (x) { return x.q; });
    },
    /* 由一道错题反查最匹配的知识点（同样的加权口径） */
    matchNode: function (q, subject) {
      var pool = bySubject[q.subject || subject] || N;
      var qt = (q.tags || []).join(' ');
      var hay = qt + ' ' + (q.stem || '') + ' ' + (q.source || '');
      var best = null, bestHit = 0;
      pool.forEach(function (n) {
        var hit = 0;
        (n.tags || []).forEach(function (t) {
          if (!t) return;
          if (qt.indexOf(t) >= 0) hit += 5;
          else if (hay.indexOf(t) >= 0) hit += 1;
        });
        if (n.name && hay.indexOf(n.name) >= 0) hit += 4;
        if (n.chapter && hay.indexOf(n.chapter) >= 0) hit += 3;
        if (hit > bestHit) { bestHit = hit; best = n; }
      });
      return best;
    },
    /* 掌握度读写（走 S 的命名空间，视图层调用时传入 store） */
    MASTER_NS: 'kpoint_mastered'
  };

